// All pixel-art textures of the diorama, generated once at module load.
import { DIORAMA } from '../config/world.js';
import { createPixelTexture, gray, setGroundMinification } from './pixelTexture.js';
import { createSeededRandom } from './random.js';

const CONCRETE_SIZE = 64;
const CONCRETE_SEAM_WIDTH = 2;

const RAW_CONCRETE_BG = '#565b60';
const RAW_CONCRETE_SEAM = '#17191b';

const ASPHALT_SIZE = 128;
const ASPHALT_BG = '#4c5054';
// A two-texel joint covers every pixel of the line, so it reads far heavier than
// the old one-texel dash did; the tone stays close to the slab to compensate.
const ASPHALT_JOINT = '#3b3f43';
const ASPHALT_SLAB = 32;
// The ground plane keeps a plain 0..1 UV, so its repeat is the tile count over the
// slab: 12 tiles across 108 m, i.e. one 9 m tile. Road surfaces use their own
// world-space UVs at the same density (see TEXTURE_TILES).
const ASPHALT_REPEAT = 12;

const SIDEWALK_SIZE = 64;
const SIDEWALK_BG = '#5c6165';
const SIDEWALK_JOINT = '#494e53';
const SIDEWALK_SLAB = 32;

const PAD_WIDTH = 128;
const PAD_HEIGHT = 64;
const PAD_BG = '#26292c';
const PAD_BORDER = '#0d0e10';
const PAD_TEXT = '#7c8286';
const PAD_TEXT_SIZE = 13;
const PAD_LABELS = ['ХОД: WASD', 'ЛЮК: [E]   УГОЛ: Q/R'];

const SIGN_WIDTH = 96;
const SIGN_HEIGHT = 16;
const SIGN_BG = '#3c4044';
const SIGN_BORDER = '#0b0c0e';
const SIGN_TEXT = '#8d9398';
const SIGN_TEXT_SIZE = 12;
// Muted Soviet courtyard shop sign: no colour, just a faint lit stencil.
const SIGN_LABEL = 'ПРОДУКТЫ';

const LIGHT_POOL_SIZE = 64;

// Beam cone alpha: opaque near the lens, transparent at the far end, so the
// volumetric cone fades out instead of ending in a hard bright rim.
const BEAM_FALLOFF_SIZE = 64;
const BEAM_FALLOFF_NEAR_ALPHA = 0.9;

// Raw concrete texture: calm monolithic tone without distracting bands.
const rawConcreteTex = createPixelTexture(CONCRETE_SIZE, CONCRETE_SIZE, (ctx, w, h) => {
    ctx.fillStyle = RAW_CONCRETE_BG;
    ctx.fillRect(0, 0, w, h);
    ctx.fillStyle = RAW_CONCRETE_SEAM;
    ctx.fillRect(0, 0, w, CONCRETE_SEAM_WIDTH);
});

// Courtyard asphalt & concrete slabs: quiet uniform mid-grey surface with subtle dark joints.
// Joints are two texels wide on purpose: at the iso camera one texel is ~0.7 buffer
// pixels, and a one-texel line survives only as broken dashes that crawl as the camera
// moves. Two texels give every pixel along the line full coverage.
const JOINT_WIDTH = 2;
const drawAsphaltJoints = (ctx: CanvasRenderingContext2D, w: number, h: number): void => {
    ctx.fillStyle = ASPHALT_BG;
    ctx.fillRect(0, 0, w, h);

    ctx.fillStyle = ASPHALT_JOINT;
    for (let i = 0; i < w; i += ASPHALT_SLAB) {
        ctx.fillRect(i, 0, JOINT_WIDTH, h);
        ctx.fillRect(0, i, w, JOINT_WIDTH);
    }
};

const groundAsphaltTex = setGroundMinification(createPixelTexture(ASPHALT_SIZE, ASPHALT_SIZE, drawAsphaltJoints));
groundAsphaltTex.repeat.set(ASPHALT_REPEAT, ASPHALT_REPEAT);

// Separate instance for the carriageway is generated by the winter road layer
// below: the carriageway is sampled with world-space UVs, so it needs its own map.

// Pavement concrete: slightly lighter slabs with a single deep joint per tile.
const sidewalkConcreteTex = setGroundMinification(createPixelTexture(SIDEWALK_SIZE, SIDEWALK_SIZE, (ctx, w, h) => {
    ctx.fillStyle = SIDEWALK_BG;
    ctx.fillRect(0, 0, w, h);

    ctx.fillStyle = SIDEWALK_JOINT;
    for (let i = 0; i < w; i += SIDEWALK_SLAB) {
        ctx.fillRect(i, 0, JOINT_WIDTH, h);
        ctx.fillRect(0, i, w, JOINT_WIDTH);
    }
}));

// World-space UV density of the surface layers (metres per texture tile).
export const TEXTURE_TILES = {
    ROAD: DIORAMA.SIZE / ASPHALT_REPEAT,
    SIDEWALK: 3.0,
    PAVING: 4.5,
    CURB: 2.4
};

// Partial rewrite for the winter dressing ported from code_artifact.html:
// settled snow has to read as broad plates (8-18 texels), never as one-texel
// noise, otherwise a snow cap boils while the camera orbits. Every plate is a
// grey level; the hue comes from the material's COLORS tone.
const WINTER_SNOW_SIZE = 64;
const WINTER_SNOW_BASE = 226;
const WINTER_SNOW_LIGHT = 238;
const WINTER_SNOW_DARK = 210;
const WINTER_SNOW_PLATES = 22;
const WINTER_SNOW_MIN = 8;
const WINTER_SNOW_MAX = 18;
const WINTER_SNOW_SEED = 0x5a17;

const winterSnowTex = createPixelTexture(WINTER_SNOW_SIZE, WINTER_SNOW_SIZE, (ctx, w, h) => {
    const random = createSeededRandom(WINTER_SNOW_SEED);
    ctx.fillStyle = gray(WINTER_SNOW_BASE);
    ctx.fillRect(0, 0, w, h);

    for (let i = 0; i < WINTER_SNOW_PLATES; i++) {
        const size = WINTER_SNOW_MIN + Math.floor(random() * (WINTER_SNOW_MAX - WINTER_SNOW_MIN));
        const x = Math.floor(random() * (w - size));
        const y = Math.floor(random() * (h - size));
        ctx.fillStyle = gray(i % 2 === 0 ? WINTER_SNOW_LIGHT : WINTER_SNOW_DARK);
        ctx.fillRect(x, y, size, size);
    }

    // Subtle crunchy firn grain and wind-packed crystalline specks
    for (let i = 0; i < 48; i++) {
        const gx = Math.floor(random() * (w - 2));
        const gy = Math.floor(random() * (h - 2));
        const gw = 1 + Math.floor(random() * 2);
        const gh = 1 + Math.floor(random() * 2);
        ctx.fillStyle = gray(i % 3 === 0 ? 245 : (i % 3 === 1 ? 214 : 202));
        ctx.fillRect(gx, gy, gw, gh);
    }
});

