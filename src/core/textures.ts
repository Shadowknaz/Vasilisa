// Continuous soft radial light pool for street fixtures with 4x4 Bayer dither.
const BAYER_4X4 = [
    [0, 8, 2, 10],
    [12, 4, 14, 6],
    [3, 11, 1, 9],
    [15, 7, 13, 5]
];

const lightPoolTex = createPixelTexture(LIGHT_POOL_SIZE, LIGHT_POOL_SIZE, (ctx, w, h) => {
    ctx.clearRect(0, 0, w, h);
    const center = w / 2;
    const radius = center - 2;

    for (let y = 0; y < h; y++) {
        for (let x = 0; x < w; x++) {
            const dx = (x - center) / radius;
            const dy = (y - center) / radius;
            const dist = Math.sqrt(dx * dx + dy * dy);
            if (dist >= 1.0) continue;

            // Optical falloff: bright center core with smooth quadratic/cubic falloff
            const core = Math.exp(-dist * dist * 3.5);
            const halo = Math.max(0.0, 1.0 - dist * dist);
            const intensity = core * 0.28 + halo * 0.12;

            // Subtle 4x4 Bayer dither for authentic PS1 dithering at the outer edge
            const dither = (BAYER_4X4[y % 4][x % 4] - 7.5) / 16.0 * 0.025;
            const alpha = Math.max(0.0, Math.min(1.0, intensity + dither));

            if (alpha > 0.008) {
                ctx.fillStyle = `rgba(255, 240, 215, ${alpha.toFixed(3)})`;
                ctx.fillRect(x, y, 1, 1);
            }
        }
    }
});

// High-fidelity searchlight ground projection with forward-throw perspective,
// hotspot core, subtle cage-shadow cross and reflector facet striations.
const SEARCHLIGHT_POOL_SIZE = 128;
const searchlightPoolTex = createPixelTexture(SEARCHLIGHT_POOL_SIZE, SEARCHLIGHT_POOL_SIZE, (ctx, w, h) => {
    ctx.clearRect(0, 0, w, h);
    const centerX = w / 2;
    // Light strikes the asphalt at a downward-forward pitch (~25 deg), so the
    // focal hotspot is set slightly back and the pool fans out forward.
    const centerY = h * 0.44;
    const radiusX = w * 0.46;
    const radiusY = h * 0.48;

    for (let y = 0; y < h; y++) {
        for (let x = 0; x < w; x++) {
            const nx = (x - centerX) / radiusX;
            // Forward fan-out: points further ahead spread out wider
            const fanWidth = 1.0 + (y / h - 0.44) * 0.28;
            const un = nx / fanWidth;
            const vn = (y - centerY) / radiusY;
            const dist = Math.sqrt(un * un + vn * vn);
            if (dist >= 1.05) continue;

            const angle = Math.atan2(vn, un);

            // 1. Physical cage cross-grille shadow: soft attenuation along the searchlight bars
            const barX = Math.min(1.0, Math.abs(un) / 0.09);
            const barY = Math.min(1.0, Math.abs(vn) / 0.09);
            const cageShadow = 0.72 + 0.28 * Math.sqrt(barX * barY);

            // 2. Parabolic reflector facet fluting (subtle radial caustics)
            const facetRibs = 1.0 + 0.05 * Math.cos(angle * 12.0) + 0.025 * Math.sin(angle * 24.0);

            // 3. Hotspot core + broad corona + feathered penumbra
            const hotspot = Math.exp(-dist * dist * 4.8);
            const corona = Math.max(0.0, 1.0 - Math.pow(dist, 1.6)) * 0.42;
            const penumbra = Math.max(0.0, 1.0 - dist) * 0.18;

            let intensity = (hotspot * 0.52 + corona + penumbra) * cageShadow * facetRibs;

            // Feathered boundary
            if (dist > 0.8) {
                const fade = Math.max(0.0, (1.05 - dist) / 0.25);
                intensity *= fade * fade;
            }

            // Bayer dither for authentic PS1 blending into asphalt and snow
            const dither = (BAYER_4X4[y % 4][x % 4] - 7.5) / 16.0 * 0.03;
            const finalAlpha = Math.max(0.0, Math.min(1.0, intensity + dither));

            if (finalAlpha > 0.006) {
                // Warm halogen / searchlight tone with bright focal white-warm core
                const r = Math.round(255);
                const g = Math.round(242 - dist * 14);
                const b = Math.round(218 - dist * 28);
                ctx.fillStyle = `rgba(${r}, ${g}, ${b}, ${finalAlpha.toFixed(3)})`;
                ctx.fillRect(x, y, 1, 1);
            }
        }
    }
});

// Textured volumetric beam falloff: longitudinal light-shaft streaks and soft
// lateral feathering simulate light cutting through winter snow haze.
const beamFalloffTex = createPixelTexture(BEAM_FALLOFF_SIZE, BEAM_FALLOFF_SIZE, (ctx, w, h) => {
    ctx.clearRect(0, 0, w, h);
    for (let y = 0; y < h; y++) {
        const v = y / (h - 1);
        // Vertical quadratic falloff from near apex to base
        const vAlpha = Math.pow(1.0 - v, 1.35) * BEAM_FALLOFF_NEAR_ALPHA;

        for (let x = 0; x < w; x++) {
            const u = x / (w - 1);
            // Longitudinal light shafts: subtle streaks of light passing through air
            const shaft1 = Math.sin(u * Math.PI * 12.0) * 0.10;
            const shaft2 = Math.cos(u * Math.PI * 24.0 + 1.2) * 0.05;
            const shaft3 = Math.sin(u * Math.PI * 6.0 - 0.7) * 0.07;
            const streakFactor = Math.max(0.2, 1.0 + shaft1 + shaft2 + shaft3);

            // Soft lateral feathering so cone boundary is misty rather than hard
            const lateral = Math.sin(u * Math.PI);
            const edgeFade = 0.82 + 0.18 * Math.pow(lateral, 0.5);

            const alpha = Math.min(1.0, Math.max(0.0, vAlpha * streakFactor * edgeFade));
            if (alpha > 0.005) {
                ctx.fillStyle = `rgba(255, 255, 255, ${alpha.toFixed(3)})`;
                ctx.fillRect(x, y, 1, 1);
            }
        }
    }
});

// Halo of a lamp: the light dissolving in the haze. Four flat rings instead of a
// smooth gradient, because a continuous ramp is exactly what the 7-bit quantizer
// turns into a visible contour; four steps dither cleanly.
const HALO_SIZE = 64;
const HALO_CENTER = HALO_SIZE / 2;
const HALO_RADIUS = 31;
const HALO_STEPS = [
    { edge: 0.3, alpha: 0.55 },
    { edge: 0.55, alpha: 0.28 },
    { edge: 0.8, alpha: 0.12 },
    { edge: 0.98, alpha: 0.04 }
];

const haloTex = createPixelTexture(HALO_SIZE, HALO_SIZE, (ctx, w, h) => {
    ctx.clearRect(0, 0, w, h);
    for (let y = 0; y < h; y++) {
        for (let x = 0; x < w; x++) {
            const dx = (x - HALO_CENTER) / HALO_RADIUS;
            const dy = (y - HALO_CENTER) / HALO_RADIUS;
            const distance = Math.sqrt(dx * dx + dy * dy);
            const step = HALO_STEPS.find((candidate) => distance < candidate.edge);
            if (!step) continue;
            ctx.fillStyle = `rgba(255, 255, 255, ${step.alpha})`;
            ctx.fillRect(x, y, 1, 1);
        }
    }
});

// Frozen wheel ruts: the carriageway keeps two polished bands where the traffic
// ran all winter. The streaks run along the V axis of the texture, and the road
// layer maps V along the direction of travel, so a rut always follows its road
// instead of lying across it at a junction.
const RUT_SIZE = 64;
const RUT_BASE = 198;
const RUT_DARK = 126;
const RUT_LIGHT = 228;
const RUT_STREAKS = 7;
const RUT_SEED = 0x3a7d;

const roadRutTex = createPixelTexture(RUT_SIZE, RUT_SIZE, (ctx, w, h) => {
    const random = createSeededRandom(RUT_SEED);
    ctx.fillStyle = gray(RUT_BASE);
    ctx.fillRect(0, 0, w, h);

    for (let index = 0; index < RUT_STREAKS; index++) {
        const x = Math.floor(random() * w);
        const width = 2 + Math.floor(random() * 6);
        ctx.fillStyle = gray(index % 3 === 0 ? RUT_LIGHT : RUT_DARK);
        ctx.fillRect(x, 0, width, h);
    }
});

